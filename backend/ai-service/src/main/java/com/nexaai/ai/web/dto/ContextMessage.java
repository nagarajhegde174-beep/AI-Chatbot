package com.nexaai.ai.web.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

/**
 * One turn of conversation context.
 *
 * <p><strong>{@link Role#SUMMARY} exists, and it is not decoration.</strong> When older turns are
 * compressed, the summary has to be labelled as a recollection rather than presented as something
 * the user actually said. A summary sent as an ordinary `USER` turn reads to the model — and to
 * anyone auditing the request — as a fresh question.
 *
 * <p><strong>No {@code SYSTEM} role.</strong> A caller must not be able to place a system
 * instruction into the history: every turn here is either something the user wrote or a
 * compression of something the user wrote. Instruction-setting is this service's business.
 *
 * @param role    never {@code SYSTEM}; see above
 * @param content the turn text. {@code SUMMARY} content is generated by this service's own
 *                {@code /summarize} endpoint, not by the caller
 */
public record ContextMessage(

        @NotNull(message = "role is required")
        Role role,

        @NotBlank(message = "content is required and must not be blank")
        @Size(max = 320_000, message = "content must be at most 320000 characters")
        String content) {

    public enum Role {
        USER,
        ASSISTANT,

        /**
         * Compressed older context.
         *
         * <p>Sent first, ahead of the verbatim turns, so the model reads it as background rather
         * than as the most recent thing that happened.
         */
        SUMMARY
    }

    /** Approximate token cost of this turn, using the same 4-characters-per-token ratio as the rest. */
    public int estimatedTokens() {
        return content == null ? 0 : content.length() / 4;
    }
}